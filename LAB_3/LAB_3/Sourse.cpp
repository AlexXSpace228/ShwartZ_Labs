// Убирает «минус ноль»: в IEEE -0.0 == 0.0, но печатается как -0.000000.
// Приятного в этом мало, поэтому перед выводом приводим -0.0 к +0.0.
double noNegZero(double v)
{
    return (v == 0.0) ? 0.0 : v;
}

// ---------------------------------------------------------------------------
//  Шаги сетки h_i = x_{i+1} - x_i (в методичке h_i, i = 1..n-1).
//
//  Сразу проверяем h_i > 0: во всех формулах встречается деление на h_i,
//  а требование x_1 < x_2 < ... < x_n — обязательное условие интерполяции.
// ---------------------------------------------------------------------------
std::vector<double> computeSteps(const std::vector<double>& x)
{
    std::vector<double> h(x.size() - 1);
    for (std::size_t i = 0; i + 1 < x.size(); ++i) {
        h[i] = x[i + 1] - x[i];
        if (!(h[i] > 0.0)) {
            throw std::runtime_error("Узлы сетки должны быть строго возрастающими");
        }
    }
    return h;
}

// ---------------------------------------------------------------------------
//  §3. МЕТОД ПРОГОНКИ  (формулы (3.1)-(3.7) методички)
//
//  Решаем систему с трёхдиагональной матрицей
//      lo[i]*x[i-1] + di[i]*x[i] + up[i]*x[i+1] = rhs[i],
//  причём lo[0] = 0 и up[n-1] = 0 (краевые уравнения содержат только одно
//  неизвестное — так записаны граничные условия).
//
//  Идея: ищем решение в виде x[i] = p[i]*x[i+1] + q[i]  (3.2).
//  Подстановка в i-е уравнение даёт рекуррентные формулы (3.4):
//      p[i] = -up[i] / (lo[i]*p[i-1] + di[i]),
//      q[i] = (rhs[i] - lo[i]*q[i-1]) / (lo[i]*p[i-1] + di[i]).
//  Стартовые значения p[0], q[0] берутся из первого уравнения — это (3.6):
//      p[0] = -up[0]/di[0],  q[0] = rhs[0]/di[0].
//
//  СПОРНЫЙ МОМЕНТ. В методичке прямой ход расписан для i = 2..n-1, а обратный
//  начинается с x_n = q_n (3.7) — как будто p_n и q_n уже есть. На самом деле
//  при up[n-1] = 0 формула (3.4) автоматически даёт p_n = 0, а q_n считается
//  по той же формуле. Поэтому здесь прогонка честно считается для ВСЕХ i,
//  включая последнее: так код проще и не надо отдельно обрабатывать край.
//
//  Почему можно не делать выбор главного элемента: у системы (2.7)
//  диагональное преобладание |di[i]| = 2 > |lo[i]| + |up[i]| = 1, поэтому
//  все ведущие элементы прогонки ненулевые и метод вычислительно устойчив.
// ---------------------------------------------------------------------------
std::vector<double> solveTridiagonal(const std::vector<double>& lo,
                                     const std::vector<double>& di,
                                     const std::vector<double>& up,
                                     const std::vector<double>& rhs,
                                     bool verbose)
{
    const std::size_t n = di.size();
    std::vector<double> p(n, 0.0), q(n, 0.0);

    // --- Прямой ход: p_i, q_i ---
    p[0] = -up[0] / di[0];
    q[0] =  rhs[0] / di[0];

    for (std::size_t i = 1; i < n; ++i) {
        const double den = lo[i] * p[i - 1] + di[i];
        if (std::fabs(den) < 1e-300) {
            throw std::runtime_error("Прогонка: нулевой ведущий элемент (матрица вырождена?)");
        }
        p[i] = -up[i] / den;
        q[i] = (rhs[i] - lo[i] * q[i - 1]) / den;
    }

    // --- Обратный ход: x_n = q_n, затем x_i = p_i*x_{i+1} + q_i ---
    std::vector<double> sol(n, 0.0);
    sol[n - 1] = q[n - 1];
    for (std::size_t i = n - 1; i-- > 0; ) {     // i = n-2, n-3, ..., 0
        sol[i] = p[i] * sol[i + 1] + q[i];
    }

    if (verbose) {
        std::cout << "\n   Прогоночные коэффициенты и решение:\n";
        // Строка "m_i" вместо общего "x_i": в этой задаче неизвестные — это
        // именно вторые производные m_i (функция solveTridiagonal универсальна,
        // но вызывается только отсюда).
        std::cout << std::setw(5) << "i"
                  << std::setw(14) << "p_i"
                  << std::setw(14) << "q_i"
                  << std::setw(14) << "m_i" << "\n";
        for (std::size_t i = 0; i < n; ++i) {
            std::cout << std::setw(5) << i + 1
                      << std::setw(14) << noNegZero(p[i])
                      << std::setw(14) << noNegZero(q[i])
                      << std::setw(14) << noNegZero(sol[i]) << "\n";
        }
    }
    return sol;
}

// ---------------------------------------------------------------------------
//  §2. ВТОРЫЕ ПРОИЗВОДНЫЕ m_i = S''(x_i)  — САМОЕ «МАТЕМАТИЧЕСКОЕ» МЕСТО.
//
//  1) Почему неизвестных m_i всего n, а не 4(n-1)?
//     Кубический многочлен на отрезке [x_i, x_{i+1}] однозначно задаётся
//     четырьмя числами: y_i, y_{i+1}, m_i, m_{i+1} (значения функции и вторые
//     производные на концах). Коэффициенты a,b,c,d через них выражаются
//     формулами (2.3), т.е. отдельно искать не нужно. Остаётся найти m_i.
//
//  2) Откуда берётся система (2.6)? Из непрерывности ПЕРВОЙ производной
//     в общих узлах: S'_{i-1}(x_i) = S'_i(x_i), i = 2..n-1  — условие (2.5).
//     Если выписать S'_i(x) через m_i, m_{i+1}, y_i, y_{i+1} и приравнять
//     левую и правую производные в узле x_i, после приведения получается
//         m_{i-1}*h_{i-1}/(h_i+h_{i-1}) + 2*m_i + m_{i+1}*h_i/(h_i+h_{i-1})
//             = 6*[ (y_{i+1}-y_i)/h_i - (y_i-y_{i-1})/h_{i-1} ] / (h_i+h_{i-1}).
//     Это и есть (2.7) с l_i = h_i/(h_i + h_{i-1}), только записанное в
//     компактной форме через разделённые разности.
//
//     ЗАМЕЧАНИЕ О ЧИСЛАХ. В методичке правая часть (2.6) расписана как
//     6y_{i-1}/(h_{i-1}(h_i+h_{i-1})) - 6y_i/(h_i*h_{i-1}) + ...
//     Это то же самое, но там сначала считаются дроби порядка 6*5/(0.005*0.01)
//     = 6*10^5, а потом из них вычитается такая же дробь — теряются 3-4
//     значащие цифры. Форма с разделёнными разностями сначала считает
//     (y_{i+1}-y_i)/h_i ~ 28, и только потом берёт разность ~1.4. Поэтому
//     в коде используется именно она.
//
//  3) Граничные условия. Уравнений (2.5) всего n-2, а неизвестных n.
//     Не хватает двух условий — это «спорный момент» любой реализации:
//     можно задать наклоны на концах (clamped), а можно потребовать нулевой
//     кривизны (natural). Методичка предписывает второе: m_1 = m_n = 0 (2.9).
//     Физический смысл — на концах балка не изогнута, «момент» равен нулю.
//
//  4) Для кода удобно сохранить матрицу размера n x n и записать краевые
//     условия как тривиальные уравнения 1*m_1 = 0 и 1*m_n = 0. Тогда индексы
//     m_i, x_i, h_i везде совпадают (в C++ они 0-based, в методичке 1-based),
//     и не нужно отдельно обрабатывать внутренние/краевые строки.
//
//  Напоминание про обозначения: m_i — это НЕ c_i из §1. В §1
//  S''(x) = 2c_i + 6d_i(x-x_i), поэтому S''(x_i) = 2c_i, то есть m_i = 2c_i.
//  Оба раздела методички описывают один и тот же сплайн.
// ---------------------------------------------------------------------------
std::vector<double> buildSecondDerivatives(const std::vector<double>& x,
                                           const std::vector<double>& y,
                                           const std::vector<double>& h,
                                           bool verbose)
{
    const std::size_t n = x.size();
    std::vector<double> lo(n, 0.0), di(n, 1.0), up(n, 0.0), rhs(n, 0.0);

    // Краевое условие (2.9) слева: m_1 = 0  ->  1*m_1 = 0.
    di[0] = 1.0;
    rhs[0] = 0.0;

    // Внутренние узлы: уравнение (2.7) для i = 2..n-1 (в C++: i = 1..n-2).
    // Для равномерной сетки h_i = 0.005 коэффициенты равны 0.5, 2, 0.5,
    // а правая часть — 3*(y_{i+1} - 2y_i + y_{i-1})/h^2 (вторая разность).
    // Например, для i = 2: 3*0.0072/0.000025 = 864.
    for (std::size_t i = 1; i + 1 < n; ++i) {
        const double denom = h[i - 1] + h[i];           // h_{i-1} + h_i
        lo[i]  = h[i - 1] / denom;                      // коэффициент при m_{i-1}
        di[i]  = 2.0;                                   // коэффициент при m_i
        up[i]  = h[i] / denom;                          // коэффициент при m_{i+1}
        rhs[i] = 6.0 * ((y[i + 1] - y[i]) / h[i]        // (y_{i+1}-y_i)/h_i
                      - (y[i] - y[i - 1]) / h[i - 1])   // (y_i-y_{i-1})/h_{i-1}
                 / denom;                               // и всё делим на (h_i+h_{i-1})
    }

    // Краевое условие (2.9) справа: m_n = 0  ->  1*m_n = 0.
    di[n - 1] = 1.0;
    rhs[n - 1] = 0.0;

    if (verbose) {
        std::cout << "\n   Матрица системы (2.7) с краевыми условиями (2.9):\n";
        std::cout << std::setw(5) << "i"
                  << std::setw(14) << "a_i"
                  << std::setw(14) << "b_i"
                  << std::setw(14) << "c_i"
                  << "   |" << std::setw(12) << "d_i" << "\n";
        for (std::size_t i = 0; i < n; ++i) {
            std::cout << std::setw(5) << i + 1
                      << std::setw(14) << lo[i]
                      << std::setw(14) << di[i]
                      << std::setw(14) << up[i]
                      << "   |" << std::setw(12) << rhs[i] << "\n";
        }
        std::cout << "   (a_i, b_i, c_i, d_i здесь — элементы СЛАУ, а не коэффициенты\n"
                     "    сплайна: так обозначены под-, главная и наддиагональ и правая часть)\n";
    }

    return solveTridiagonal(lo, di, up, rhs, verbose);
}

// ---------------------------------------------------------------------------
//  Коэффициенты сплайна по найденным m_i — формулы (2.3):
//      a_i = y_i
//      c_i = m_i / 2
//      d_i = (m_{i+1} - m_i) / (6*h_i)
//      b_i = (y_{i+1} - y_i)/h_i - h_i*m_i/3 - h_i*m_{i+1}/6
//
//  Вывод b_i: подставляем x = x_{i+1} (t = h_i) в S_i = a + b*t + c*t^2 + d*t^3
//  и требуем S_i(x_{i+1}) = y_{i+1}:
//      y_i + b*h + (m_i/2)*h^2 + ((m_{i+1}-m_i)/(6h))*h^3 = y_{i+1}
//      b*h = (y_{i+1}-y_i) - h^2*(m_i/2 + (m_{i+1}-m_i)/6)
//          = (y_{i+1}-y_i) - h^2*(m_i/3 + m_{i+1}/6)
//  — отсюда формула для b_i.
//
//  ПОЧЕМУ d_i такие большие (до 1.6*10^4)? Потому что это коэффициент при t^3,
//  а t на нашем отрезке не превосходит h = 0.005. Вклад d_i*t^3 <= 1.6e4*1.25e-7
//  ~ 0.002, т.е. сравним с пятым знаком после запятой — всё нормально, это не
//  ошибка и не «разболтанность» решения. Размерности: b ~ y/x, c ~ y/x^2,
//  d ~ y/x^3, поэтому их численные значения так сильно и различаются.
// ---------------------------------------------------------------------------
std::vector<Cubic> buildSpline(const std::vector<double>& x,
                               const std::vector<double>& y,
                               const std::vector<double>& h,
                               const std::vector<double>& m)
{
    const std::size_t n = x.size();
    std::vector<Cubic> s(n - 1);
    for (std::size_t i = 0; i + 1 < n; ++i) {
        s[i].a = y[i];
        s[i].c = m[i] / 2.0;
        s[i].d = (m[i + 1] - m[i]) / (6.0 * h[i]);
        s[i].b = (y[i + 1] - y[i]) / h[i] - h[i] * m[i] / 3.0 - h[i] * m[i + 1] / 6.0;
    }
    return s;
}

// ---------------------------------------------------------------------------
//  Поиск отрезка [x_i, x_{i+1}], содержащего X*.
//  Узлы упорядочены, поэтому достаточно линейного поиска (при больших n
//  взяли бы std::upper_bound).
//
//  Тонкость: если X* совпал с узлом, подойдёт любой из двух соседних отрезков
//  (значения совпадают из-за непрерывности). Если X* = x_n (правый конец),
//  возвращаем последний отрезок — иначе индекс выйдет за границу массива.
//  Выход за [x_1, x_n] — это экстраполяция, а не интерполяция: по заданию её
//  быть не должно, поэтому бросаем исключение.
// ---------------------------------------------------------------------------
std::size_t findSegment(const std::vector<double>& x, double xs)
{
    if (xs < x.front() || xs > x.back()) {
        throw std::runtime_error("X* вне отрезка интерполяции");
    }
    if (xs == x.back()) {
        return x.size() - 2;
    }
    for (std::size_t i = 0; i + 1 < x.size(); ++i) {
        if (xs >= x[i] && xs <= x[i + 1]) {
            return i;
        }
    }
    return x.size() - 2;   // сюда попасть невозможно, но компилятор спокоен
}

// ---------------------------------------------------------------------------
//  Значение сплайна по схеме Горнера:
//      S = a + b*t + c*t^2 + d*t^3 = a + t*(b + t*(c + t*d)).
//  Это и быстрее (3 умножения вместо 5), и точнее: нет отдельного вычисления
//  больших степеней t, которые потом складываются.
//
//  t считается как X* - x_i, т.е. в ЛОКАЛЬНОЙ системе координат. Так и надо:
//  если раскрыть скобки и считать в глобальной x, придётся вычитать почти
//  равные числа порядка 1.4; здесь же t ~ 0.0012. В double это ещё безопасно,
//  но во float разность 1.3862 - 1.3850 потеряла бы 3-4 значащие цифры.
// ---------------------------------------------------------------------------
double evalCubic(const Cubic& s, double t)
{
    return s.a + t * (s.b + t * (s.c + t * s.d));
}

// ---------------------------------------------------------------------------
//  Независимая проверка: формула (2.4) из методички, записанная через m_i:
//
//    S_i(x) = m_i*(x-x_i)/(6h_i)*[h_i^2 - (x-x_i)^2]
//           + (m_i/2)*(x-x_i)*(x-x_{i+1})
//           + m_{i+1}*(x-x_i)/(6h_i)*[(x-x_i)^2 - h_i^2]
//           + y_{i+1}*(x-x_i)/h_i
//           + y_i*(x_{i+1}-x)/h_i
//
//  Она получается прямой подстановкой (2.3) в (2.1) и выглядит странно:
//  например, второе слагаемое при x = x_i и при x = x_{i+1} равно нулю,
//  а нужно оно, чтобы «добавить» к кривизне ровно m_i/2. Но проверить её
//  полезно: если обе формулы дают одно и то же, значит и m_i, и коэффициенты
//  посчитаны верно (формулы внешне совсем не похожи).
// ---------------------------------------------------------------------------
double evalByFormula24(const std::vector<double>& x,
                       const std::vector<double>& y,
                       const std::vector<double>& h,
                       const std::vector<double>& m,
                       std::size_t i,
                       double xs)
{
    const double hi = h[i];
    const double t  = xs - x[i];          // x - x_i
    const double s  = hi - t;             // x_{i+1} - x

    return m[i] * t / (6.0 * hi) * (hi * hi - t * t)
         + 0.5 * m[i] * t * (t - hi)
         + m[i + 1] * t / (6.0 * hi) * (t * t - hi * hi)
         + y[i + 1] * t / hi
         + y[i] * s / hi;
}

// ---------------------------------------------------------------------------
//  Проверки. Они нужны не «для галочки», а чтобы поймать ошибки в индексации
//  (самая частая причина неверного ответа в этой лабораторной).
//
//  1) Интерполяция: S(x_i) должно совпадать с y_i. По построению a_i = y_i,
//     поэтому проверка контролирует в основном правые концы отрезков.
//  2) Непрерывность первой производной:
//         S'_i(x_{i+1}) = b_i + 2c_i*h_i + 3d_i*h_i^2  должно быть равно b_{i+1}.
//  3) Непрерывность второй производной:
//         S''_i(x_{i+1}) = 2c_i + 6d_i*h_i  должно быть равно 2c_{i+1} = m_{i+1}.
//  В точной арифметике все три невязки — нули; в double они порядка 1e-12
//  (это и есть накопленная погрешность решения СЛАУ).
// ---------------------------------------------------------------------------
double maxInterpolationError(const std::vector<double>& x,
                             const std::vector<double>& y,
                             const std::vector<Cubic>& s)
{
    double worst = 0.0;
    const std::size_t n = x.size();
    for (std::size_t i = 0; i + 1 < n; ++i) {
        worst = std::max(worst, std::fabs(evalCubic(s[i], 0.0) - y[i]));
        const double h = x[i + 1] - x[i];
        worst = std::max(worst, std::fabs(evalCubic(s[i], h) - y[i + 1]));
    }
    return worst;
}

double maxFirstDerivativeJump(const std::vector<double>& x,
                              const std::vector<Cubic>& s)
{
    double worst = 0.0;
    for (std::size_t i = 0; i + 1 < s.size(); ++i) {
        const double h = x[i + 1] - x[i];
        const double left  = s[i].b + 2.0 * s[i].c * h + 3.0 * s[i].d * h * h;
        const double right = s[i + 1].b;
        worst = std::max(worst, std::fabs(left - right));
    }
    return worst;
}

double maxSecondDerivativeJump(const std::vector<double>& x,
                               const std::vector<Cubic>& s)
{
    double worst = 0.0;
    for (std::size_t i = 0; i + 1 < s.size(); ++i) {
        const double h = x[i + 1] - x[i];
        const double left  = 2.0 * s[i].c + 6.0 * s[i].d * h;
        const double right = 2.0 * s[i + 1].c;
        worst = std::max(worst, std::fabs(left - right));
    }
    return worst;
}

